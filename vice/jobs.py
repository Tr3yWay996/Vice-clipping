"""Daemon-owned serial media queue with atomic versioned history and recovery."""
from __future__ import annotations
import asyncio
import copy
import json
import logging
import os
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from .processing import MediaProcess
from .runtime import actual_home_dir

JOBS_PATH = actual_home_dir() / '.local' / 'share' / 'vice' / 'jobs.json'
TERMINAL = {'completed', 'failed', 'cancelled', 'interrupted'}
log = logging.getLogger(__name__)


def remove_partial(path):
    try:
        Path(path).unlink(missing_ok=True)
    except OSError as exc:
        log.warning('Could not remove partial processing output %s: %s', path, exc)


def now():
    return datetime.now(timezone.utc).isoformat()


class ProcessingQueue:
    def __init__(self, broadcast, runner, path=None, lock=None):
        self.path = path if path is not None else JOBS_PATH
        self.broadcast = broadcast
        self.runner = runner
        self.lock = lock or asyncio.Lock()
        self.jobs: list[dict] = []
        self.worker = None
        self.task = None
        self.current = None
        self.process = MediaProcess()
        self.process.on_state = self._process_state
        self.stopping = False
        self._cancelling = False
        self._changed = asyncio.Event()
        self.load()

    def load(self):
        if not self.path.exists():
            return
        data = json.loads(self.path.read_text())
        if data.get('version') != 1 or not isinstance(data.get('jobs'), list):
            raise ValueError('Unsupported processing history version')
        self.jobs = data['jobs']
        for job in self.jobs:
            if job['status'] == 'processing' or (job['status'] == 'paused' and job.get('started_at')):
                job.update(status='interrupted', can_pause=False, finished_at=now(),
                           error='Daemon stopped during processing. Retry starts a new encode.')
                for tmp in job.get('temporary_paths', []):
                    # These paths were generated by the daemon, never accepted
                    # from a public request. An unfinished output is never used.
                    remove_partial(tmp)
        self.save()

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.path.with_suffix('.json.tmp')
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, 'w') as stream:
            json.dump({'version': 1, 'jobs': self.jobs}, stream)
            stream.flush()
            os.fsync(stream.fileno())
        tmp.replace(self.path)

    def snapshot(self):
        # Commands, source paths and replay payloads stay in local persistence;
        # the UI receives only display metadata and supported capabilities.
        return [copy.deepcopy({k: v for k, v in job.items() if k not in {'payload', 'temporary_paths'}})
                for job in self.jobs]

    async def changed(self):
        self.save()
        self._changed.set()
        self._changed = asyncio.Event()
        await self.broadcast({'type': 'jobs_changed', 'jobs': self.snapshot()})

    async def wait(self, jid):
        while True:
            changed = self._changed
            job = next((j for j in self.jobs if j['id'] == jid), None)
            if not job:
                raise ValueError('Job not found')
            if job['status'] in TERMINAL:
                return job
            await changed.wait()

    def start(self):
        if not self.stopping and (self.worker is None or self.worker.done()):
            self.worker = asyncio.create_task(self._work())

    async def submit(self, operation, source_name, payload, *, output_path=None, source_revision=None, duration=None, source_media_ids=None, mode=None):
        if self.stopping:
            raise ValueError('Processing queue is stopping')
        if output_path and any(j.get('output_path') == str(output_path) and j['status'] not in TERMINAL for j in self.jobs):
            raise ValueError('That output already belongs to a queued job')
        job = dict(id=uuid.uuid4().hex, operation=operation, name=source_name,
                   source_revision=source_revision, source_media_ids=list(source_media_ids or []), mode=mode, output_path=str(output_path) if output_path else None,
                   created_at=now(), started_at=None, finished_at=None, duration=duration,
                   progress=None, elapsed=0, remaining=None, speed=None, stage='queued',
                   status='queued', error=None, result_path=None, can_pause=False,
                   payload=copy.deepcopy(payload), temporary_paths=[])
        self.jobs.append(job)
        await self.changed()
        self.start()
        return copy.deepcopy({k:v for k,v in job.items() if k not in {'payload', 'temporary_paths'}})

    def _process_state(self):
        if self.current:
            self.current['can_pause'] = self.process.proc is not None and self.process.proc.returncode is None

    async def stage(self, stage, temporary=None):
        if not self.current:
            return
        self.current.update(stage=stage, progress=None, remaining=None, speed=None)
        self._stage_clock = time.monotonic()
        self._stage_paused = self._paused_time
        if temporary:
            value = str(temporary)
            if value not in self.current['temporary_paths']:
                self.current['temporary_paths'].append(value)
        await self.changed()

    async def progress(self, fraction, speed=None):
        if self.current:
            job = self.current
            clock = self._paused_at if self._paused_at is not None else time.monotonic()
            elapsed = max(0, clock - self._clock - self._paused_time)
            stage_elapsed = max(0, clock - self._stage_clock - (self._paused_time - self._stage_paused))
            fraction = max(0, min(.999, fraction))
            job.update(progress=fraction, speed=speed, elapsed=elapsed,
                       remaining=(stage_elapsed * (1 - fraction) / fraction) if fraction > .01 else None,
                       can_pause=self.process.proc is not None)
            await self.changed()

    async def _work(self):
        while not self.stopping:
            job = next((j for j in self.jobs if j['status'] == 'queued'), None)
            if job is None:
                return
            # Also serialize legacy preview/audio preparations through this
            # same resource slot, without surfacing thumbnail/probe jobs.
            async with self.lock:
                if self.stopping or job['status'] != 'queued':
                    continue
                self.current = job
                self._cancelling = False
                self._clock, self._paused_time = time.monotonic(), 0
                self._stage_clock, self._stage_paused, self._paused_at = self._clock, 0, None
                job.update(status='processing', started_at=now(), stage='preparing')
                await self.changed()
                self.task = asyncio.create_task(self.runner(job))
                try:
                    result = await self.task
                    job.update(status='completed', progress=1, result_path=str(result), stage='completed', error=None)
                except asyncio.CancelledError:
                    job.update(status='interrupted' if self.stopping else 'cancelled', stage='stopped')
                except Exception as exc:
                    job.update(status='failed', error=str(exc), stage='failed')
                finally:
                    job.update(finished_at=now(), can_pause=False, remaining=None,
                               elapsed=max(0, (self._paused_at if self._paused_at is not None else time.monotonic()) - self._clock - self._paused_time))
                    for tmp in job['temporary_paths']:
                        remove_partial(tmp)
                    self.task = None
                    self.current = None
                    await self.changed()

    async def control(self, jid, action):
        job = next((j for j in self.jobs if j['id'] == jid), None)
        if job is None:
            raise ValueError('Job not found')
        state = job['status']
        if action == 'remove' and state in TERMINAL:
            self.jobs.remove(job)
        elif action == 'retry' and state in {'failed','interrupted','cancelled'}:
            return await self.submit(job['operation'], job['name'], job['payload'], output_path=job.get('output_path'),
                                     source_revision=job.get('source_revision'), duration=job.get('duration'),
                                     source_media_ids=job.get('source_media_ids'), mode=job.get('mode'))
        elif action == 'pause' and state == 'queued':
            job['status'] = 'paused'
        elif action == 'pause' and state == 'processing' and self.process.pause():
            self._paused_at = time.monotonic()
            job['status'] = 'paused'
        elif action == 'resume' and state == 'paused':
            if job is self.current:
                if not self.process.resume():
                    raise ValueError('This stage cannot be resumed')
                self._paused_time += time.monotonic() - self._paused_at
                self._paused_at = None
                job['status'] = 'processing'
            else:
                job['status'] = 'queued'
        elif action == 'cancel' and state not in TERMINAL:
            if job is self.current and job['stage'] == 'saving':
                raise ValueError('Final file publication cannot be cancelled')
            if job is self.current:
                if self.task and not self.task.done():
                    if not self._cancelling:
                        self._cancelling = True
                        self.task.cancel()
                    await asyncio.shield(asyncio.gather(self.task, return_exceptions=True))
                # Worker performs final state transition after process cleanup.
                return job
            job.update(status='cancelled', finished_at=now(), can_pause=False)
        else:
            raise ValueError('This control is unavailable during the current processing stage')
        await self.changed()
        self.start()
        return job

    async def stop(self):
        self.stopping = True
        if self.current is not None:
            if self.task and not self.task.done() and not self._cancelling:
                self._cancelling = True
                self.task.cancel()
        elif self.worker and not self.worker.done():
            self.worker.cancel()
        if self.worker:
            await asyncio.shield(asyncio.gather(self.worker, return_exceptions=True))
        self.save()
